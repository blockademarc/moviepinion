    <h1>AGB</h1>

    <h2>Nutzung des Portals</h2>
    <p>MoviePinion kann kostenlos genutzt werden. Das Portal dient dem Anzeigen, Suchen, Ergänzen und Kommentieren von Filmen.</p>

    <h2>Benutzerkonto</h2>
    <p>Für das Hinzufügen von Filmen, das Schreiben von Kommentaren und das Senden von Anfragen ist ein Benutzerkonto erforderlich.</p>

    <h2>Kommentare</h2>
    <p>Kommentare sollen sich auf den jeweiligen Film beziehen. Unpassende, beleidigende oder missbräuchliche Beiträge können entfernt werden.</p>

    <h2>Filminhalte</h2>
    <p>Filmdaten, Poster und Beschreibungen können aus externen Quellen stammen. Für Vollständigkeit und Aktualität der Angaben wird keine Gewähr übernommen.</p>
</section>

    <h1>About</h1>
    <p><strong>MoviePinion</strong> ist ein Filmarchiv für alle, die Filme suchen, entdecken und kommentieren möchten.</p>
    <p>In der Galerie finden Sie gespeicherte Filme mit Poster, Jahr, Besetzung, Genre und weiteren Details. Über die Suche können Sie schnell nach Titeln, Schauspielern, Regisseuren oder Genres filtern.</p>
    <p>Mit einem Benutzerkonto können Sie neue Filme zum Archiv hinzufügen, gespeicherte Filmdateien herunterladen, Kommentare schreiben und eigene Anfragen verwalten.</p>
